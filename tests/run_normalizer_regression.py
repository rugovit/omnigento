#!/usr/bin/env python3
"""Zero-dependency regression tests for legacy instruction normalization."""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_KIT = REPO_ROOT / "omnigento"
GENERATED_MARKER = "<!-- GENERATED BY omnigento/bin/sync_ai_instructions.py; DO NOT EDIT DIRECTLY -->"
LEGACY_GENERATED_MARKER = "<!-- GENERATED BY instruction-seed/bin/sync_ai_instructions.py; DO NOT EDIT DIRECTLY -->"
BEGIN_BLOCK = "<!-- BEGIN GENERATED INSTRUCTIONS -->"
END_BLOCK = "<!-- END GENERATED INSTRUCTIONS -->"


class RegressionError(AssertionError):
    pass


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def read_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def copy_kit(target: Path) -> None:
    kit = target / "omnigento"
    kit.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOURCE_KIT / "HOW_TO_RUN.md", kit / "HOW_TO_RUN.md")
    for name in ["bin", "lib", "meta", "docs"]:
        shutil.copytree(SOURCE_KIT / name, kit / name)


def run(repo: Path, *args: str, expect_ok: bool = True) -> subprocess.CompletedProcess[str]:
    cmd = [sys.executable, "omnigento/bin/normalize_legacy_instructions.py", *args]
    result = subprocess.run(cmd, cwd=repo, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if expect_ok and result.returncode != 0:
        raise RegressionError(
            f"command failed: {' '.join(cmd)}\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
    if not expect_ok and result.returncode == 0:
        raise RegressionError(f"command unexpectedly passed: {' '.join(cmd)}\nstdout:\n{result.stdout}")
    return result


def run_sync(repo: Path, *args: str, expect_ok: bool = True) -> subprocess.CompletedProcess[str]:
    cmd = [sys.executable, "omnigento/bin/sync_ai_instructions.py", *args]
    result = subprocess.run(cmd, cwd=repo, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if expect_ok and result.returncode != 0:
        raise RegressionError(
            f"command failed: {' '.join(cmd)}\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
    if not expect_ok and result.returncode == 0:
        raise RegressionError(f"command unexpectedly passed: {' '.join(cmd)}\nstdout:\n{result.stdout}")
    return result


def role_counts(repo: Path, run_id: str) -> dict[str, int]:
    inventory = read_json(repo / "omnigento" / ".tmp" / "normalize" / run_id / "inventory.json")
    counts: dict[str, int] = {}
    if not isinstance(inventory, list):
        raise RegressionError("inventory.json must be a list")
    for record in inventory:
        role = record["role"]
        counts[role] = counts.get(role, 0) + 1
    return counts


def manifest(repo: Path, run_id: str) -> dict[str, object]:
    value = read_json(repo / "omnigento" / ".tmp" / "normalize" / run_id / "manifest.json")
    if not isinstance(value, dict):
        raise RegressionError("manifest.json must be an object")
    return value


def assert_equal(actual: object, expected: object, label: str) -> None:
    if actual != expected:
        raise RegressionError(f"{label}: expected {expected!r}, got {actual!r}")


def assert_contains(text: str, needle: str, label: str) -> None:
    if needle not in text:
        raise RegressionError(f"{label}: expected output to contain {needle!r}\n{text}")


def assert_not_contains(text: str, needle: str, label: str) -> None:
    if needle in text:
        raise RegressionError(f"{label}: expected output not to contain {needle!r}\n{text}")



def test_normalized_project_noop(base: Path) -> None:
    repo = base / "normalized-project"
    create_normalized_project(repo)
    run_id = "normalized-noop"

    run(repo, "--inventory", "--run-id", run_id)
    counts = role_counts(repo, run_id)
    assert_equal(counts.get("legacy_input", 0), 0, "normalized legacy_input count")
    assert_equal(counts.get("canonical", 0), 2, "normalized canonical count")

    run(repo, "--classify", "--run-id", run_id, "--runtime", "mock")
    run(repo, "--merge", "--run-id", run_id)
    run(repo, "--propose", "--run-id", run_id)
    run(repo, "--apply", "--run-id", run_id)
    data = manifest(repo, run_id)
    assert_equal(data.get("classified_count"), 0, "normalized classified count")
    assert_equal(data.get("proposed_file_count"), 0, "normalized proposed count")
    assert_equal(data.get("applied_file_count"), 0, "normalized applied count")


def test_legacy_generated_markers_not_legacy_input(base: Path) -> None:
    repo = base / "legacy-generated-markers"
    create_normalized_project(repo)
    for path in [
        repo / "AGENTS.md",
        repo / "CLAUDE.md",
        repo / ".cursor" / "rules" / "example.mdc",
        repo / ".claude" / "rules" / "example.md",
    ]:
        text = path.read_text(encoding="utf-8").replace(GENERATED_MARKER, LEGACY_GENERATED_MARKER)

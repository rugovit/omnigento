def test_legacy_overlap_pipeline(base: Path) -> None:
    repo = base / "legacy-overlap"
    classifier = create_legacy_overlap_project(repo)
    run_id = "legacy-overlap"

    run(repo, "--inventory", "--run-id", run_id)
    counts = role_counts(repo, run_id)
    assert_equal(counts.get("legacy_input", 0), 2, "legacy overlap input count")

    run(
        repo,
        "--classify",
        "--run-id",
        run_id,
        "--runtime",
        "command",
        "--classifier-command",
        f"{sys.executable} {classifier}",
    )
    run(repo, "--merge", "--run-id", run_id)
    run(repo, "--propose", "--run-id", run_id)

    data = manifest(repo, run_id)
    assert_equal(data.get("classified_count"), 2, "legacy classified count")
    assert_equal(data.get("merged_rule_count"), 3, "legacy merged count")
    assert_equal(data.get("conflict_count"), 1, "legacy conflict count")
    assert_equal(data.get("discarded_count"), 1, "legacy discarded count")
    assert_equal(data.get("proposed_file_count"), 2, "legacy proposed count")
    assert_equal(data.get("unsupported_rule_count"), 1, "legacy unsupported count")

    refused = run(repo, "--apply", "--run-id", run_id, expect_ok=False)
    if "unsupported rules" not in refused.stderr:
        raise RegressionError("apply refusal did not mention unsupported rules")

    run(repo, "--apply", "--run-id", run_id, "--allow-unsupported")
    assert (repo / ".github" / "instructions" / "legacy-normalize-safety-test.instructions.md").is_file()
    assert (repo / ".github" / "instructions" / "legacy-normalize-plugin-test.instructions.md").is_file()
    data = manifest(repo, run_id)
    assert_equal(data.get("applied_file_count"), 2, "legacy applied count")


